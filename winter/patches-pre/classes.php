 * WHY THIS FILE EXISTS — TWO INTERLOCKING REASONS
 * -------------------------------------------------
 *
 * 1. CASE MISMATCH: WinterCMS module directories use lowercase names (traits/, classes/,
 *    models/, behaviors/, etc.) while PHP namespaces use StudlyCase (Traits, Classes...).
 *    Composer's PSR-4 autoloader is case-sensitive on Linux: it maps System\Traits\Foo to
 *    modules/system/Traits/Foo.php (capital T), which does not exist. All WinterCMS module
 *    classes with intermediate namespace parts therefore FAIL to resolve via Composer on Linux.
 *
 *    Winter's own ClassLoader handles this correctly via strtolower() in its autoloadedPackages
 *    lookup. But autoloadPackage() is only called when System\ServiceProvider::register() runs.
 *    Classes needed before that point must be pre-seeded here.
 *
 * 2. SYMLINKED MODULES: Composer path repos install local modules as symlinks:
 *    modules/acorn → /home/<user>/Software/GitHub/infrastructure/
 *    modules/dbauth → /home/<user>/Software/GitHub/dbauth/
 *    PHP-FPM (www-data) uses realpath() to validate paths. If the home directory lacks the
 *    execute bit for "others" (drwxr-x--- is the Linux default), realpath() returns false and
 *    Composer cannot resolve those symlinked module classes at all. The fix is:
 *    sudo chmod o+x /home/<user>/   (adds traverse permission, not listing)
 *    The ClassLoader uses the same realpath() check, so this also affects manifest entries.
 *
 * RESULT: This file must contain the module classes for System, Backend, Cms, Acorn, and
 * DBAuth so they are resolvable during the bootstrap phase before register() has run.
 * Plugin classes (acorn/calendar, winter/user etc.) do not need to be here — they are
 * registered by PluginManager::registerAll() which runs inside System\ServiceProvider::register().
 *
 * AUTO-GROWN AFTER FIRST BOOT
 * ----------------------------
 * Once the app boots successfully, ClassLoader::build() rewrites this file with every class
 * the ClassLoader resolved during that session. The file then grows to reflect actual usage.
 * Stale entries (removed plugins etc.) are safe: isRealFilePath() uses realpath() to validate
 * each entry and silently skips any path that no longer exists.
 */
